import AppKit

struct ClipItem: Identifiable, Equatable {
    enum Kind: Equatable { case text, link, image, files }

    let id: UUID
    let kind: Kind
    let text: String?
    let image: NSImage?
    let files: [URL]
    let date: Date
    let sourceApp: String?

    var preview: String {
        switch kind {
        case .text, .link:
            return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ⏎ ")
        case .image:
            return image.map { "Bild · \(Int($0.size.width))×\(Int($0.size.height))" } ?? "Bild"
        case .files:
            return files.count == 1 ? files[0].lastPathComponent : "\(files.count) filer"
        }
    }

    var symbol: String {
        switch kind {
        case .text: "text.alignleft"
        case .link: "link"
        case .image: "photo"
        case .files: "doc"
        }
    }

    static func == (lhs: ClipItem, rhs: ClipItem) -> Bool { lhs.id == rhs.id }
}

/// A clipboard queue: everything you copy lands here. Click an item to put it back on the
/// clipboard; in queue mode each ⌘V moves the clipboard on to the next item, so a run of copies
/// can be pasted in order.
@MainActor @Observable
final class ClipboardService {
    private(set) var items: [ClipItem] = []
    /// The item that's on the clipboard now, if it came from the queue.
    private(set) var currentID: UUID?
    var queueMode: Bool {
        didSet {
            UserDefaults.standard.set(queueMode, forKey: Self.queueKey)
            updatePasteMonitor()
            if queueMode, currentID == nil, let first = items.last { use(first) }
        }
    }

    @ObservationIgnored private let settings: AppSettings
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var pasteMonitor: Any?

    private static let queueKey = "clipboardQueueMode"
    private static let textKey = "clipboardTextHistory"
    /// Password managers mark secrets with these; they never enter the queue.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    init(settings: AppSettings) {
        self.settings = settings
        queueMode = UserDefaults.standard.bool(forKey: Self.queueKey)
        restore()
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
        updatePasteMonitor()
    }

    func stop() {
        timer?.invalidate()
        if let pasteMonitor { NSEvent.removeMonitor(pasteMonitor) }
    }

    /// Oldest first – the order a queue is pasted in.
    var queue: [ClipItem] { items.reversed() }

    var nextItem: ClipItem? {
        let queue = queue
        guard let currentID, let index = queue.firstIndex(where: { $0.id == currentID }), index + 1 < queue.count else {
            return currentID == nil ? queue.first : nil
        }
        return queue[index + 1]
    }

    // MARK: Actions

    /// Puts an item on the clipboard and makes it the current one.
    func use(_ item: ClipItem) {
        let board = NSPasteboard.general
        board.clearContents()
        switch item.kind {
        case .text: board.setString(item.text ?? "", forType: .string)
        case .link:
            board.setString(item.text ?? "", forType: .string)
            if let url = URL(string: item.text ?? "") { board.writeObjects([url as NSURL]) }
        case .image: if let image = item.image { board.writeObjects([image]) }
        case .files: board.writeObjects(item.files.map { $0 as NSURL })
        }
        lastChangeCount = board.changeCount // our own write isn't a new copy
        currentID = item.id
    }

    func advance() {
        guard let next = nextItem else { return }
        use(next)
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        if currentID == item.id { currentID = nil }
        save()
    }

    func clear() {
        items = []
        currentID = nil
        save()
    }

    // MARK: Watching the clipboard

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChangeCount else { return }
        lastChangeCount = board.changeCount
        guard settings.showClipboardTab else { return }
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        var item: ClipItem?
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = ClipItem(id: UUID(), kind: .files, text: nil, image: nil, files: urls, date: Date(), sourceApp: source)
        } else if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(" ") && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
            item = ClipItem(id: UUID(), kind: isLink ? .link : .text, text: text, image: nil, files: [], date: Date(), sourceApp: source)
        } else if let image = NSImage(pasteboard: board) {
            item = ClipItem(id: UUID(), kind: .image, text: nil, image: image, files: [], date: Date(), sourceApp: source)
        }
        guard let item else { return }

        // Copying the same text again moves it to the top instead of adding a duplicate.
        if let text = item.text { items.removeAll { $0.text == text } }
        items.insert(item, at: 0)
        if items.count > settings.clipboardLimit { items.removeLast(items.count - settings.clipboardLimit) }
        // A fresh copy is what's on the clipboard now; in queue mode the run continues from it.
        currentID = item.id
        save()
    }

    /// In queue mode, every ⌘V (anywhere) loads the next item once the paste has happened.
    private func updatePasteMonitor() {
        if let pasteMonitor { NSEvent.removeMonitor(pasteMonitor) }
        pasteMonitor = nil
        guard queueMode else { return }
        pasteMonitor = NSEvent.addGlobalMonitorForEvents(matching: .keyDown) { [weak self] event in
            guard event.charactersIgnoringModifiers?.lowercased() == "v",
                  event.modifierFlags.intersection(.deviceIndependentFlagsMask) == .command else { return }
            Task { @MainActor [weak self] in
                // Give the app a moment to read the clipboard before it changes.
                try? await Task.sleep(for: .milliseconds(250))
                guard let self, self.queueMode else { return }
                self.advance()
            }
        }
    }

    // MARK: Persistence (text and links only; images and files stay in memory)

    private func save() {
        let stored: [[String: Any]] = items.compactMap { item in
            guard let text = item.text else { return nil }
            return ["text": text, "link": item.kind == .link, "date": item.date.timeIntervalSince1970,
                    "source": item.sourceApp ?? ""]
        }
        UserDefaults.standard.set(stored, forKey: Self.textKey)
    }

    private func restore() {
        let stored = UserDefaults.standard.array(forKey: Self.textKey) as? [[String: Any]] ?? []
        items = stored.compactMap { entry in
            guard let text = entry["text"] as? String else { return nil }
            let source = entry["source"] as? String
            return ClipItem(id: UUID(), kind: entry["link"] as? Bool == true ? .link : .text, text: text, image: nil,
                            files: [], date: Date(timeIntervalSince1970: entry["date"] as? Double ?? 0),
                            sourceApp: source?.isEmpty == false ? source : nil)
        }
    }
}
